/* eslint-disable @typescript-eslint/no-require-imports */
const { chromium } = require(process.env.RABT_PLAYWRIGHT_PATH || "@playwright/test");
const assert = require("node:assert/strict");
const fs = require("node:fs");

(async () => {
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: "light" });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const base = process.env.RABT_TEST_URL || "http://localhost:3000";
  fs.mkdirSync("output/review", { recursive: true });
  await page.goto(base, { waitUntil: "networkidle" });
  await page.locator(".product-photo").first().waitFor();
  assert.equal(await page.locator(".hero h1").innerText(), "تقنيتك الجاية،\nإلها رابط.");
  await page.locator("img").evaluateAll((images) => Promise.all(images.map((img) => { img.loading = "eager"; return img.decode(); })));
  for (const img of await page.locator("img").all()) assert(await img.evaluate((el) => el.complete && el.naturalWidth > 0), await img.getAttribute("src"));
  await page.screenshot({ path: "output/review/home-light.png", fullPage: true });
  await page.getByRole("button", { name: "تفعيل الوضع الداكن" }).click();
  assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
  await page.reload({ waitUntil: "networkidle" });
  assert.equal(await page.locator("html").getAttribute("data-theme"), "dark");
  await page.screenshot({ path: "output/review/home-dark.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Mobile horizontal overflow");
  await page.screenshot({ path: "output/review/home-mobile.png", fullPage: true });
  await page.goto(base + "/register", { waitUntil: "networkidle" });
  await page.getByRole("button", { name: "حساب فردي", exact: false }).click();
  const unique = Date.now();
  const listingTitle = `جهاز اختبار الواجهة ${unique}`;
  await page.getByLabel("الاسم", { exact: true }).fill("اختبار الواجهة");
  await page.getByLabel("البريد الإلكتروني", { exact: true }).fill(`qa-ui-${unique}@example.test`);
  await page.locator('input[type="password"]').fill("Rabt-Browser-82!");
  await page.getByLabel("رقم الهاتف", { exact: true }).fill("0791234567");
  await page.getByLabel("المدينة", { exact: true }).selectOption("Amman");
  await page.locator('input[type="checkbox"]').check();
  await page.getByRole("button", { name: "إنشاء الحساب", exact: true }).click();
  await page.waitForURL("**/account");
  await page.goto(base + "/sell", { waitUntil: "networkidle" });
  await page.getByLabel("العنوان", { exact: true }).fill(listingTitle);
  await page.getByLabel("المدينة", { exact: true }).selectOption("Amman");
  await page.getByLabel("السعر بالدينار", { exact: true }).fill("55");
  await page.getByLabel("الوصف", { exact: true }).fill("منتج تجريبي لفحص عمل النشر من المتصفح بشكل كامل.");
  await page.locator('input[type="file"]').setInputFiles("public/images/phone.webp");
  await page.getByRole("button", { name: "معاينة الإعلان", exact: true }).click();
  await page.getByRole("button", { name: "نشر الإعلان", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "تم حفظ إعلانك ونشره بنجاح" }).waitFor();
  await page.goto(base + "/products?search=" + encodeURIComponent(listingTitle), { waitUntil: "networkidle" });
  await page.locator(".product-card").filter({ hasText: listingTitle }).waitFor();
  const card = page.locator(".product-card").filter({ hasText: listingTitle });
  assert((await card.locator("img").getAttribute("src")).startsWith("data:image/webp"));
  const savedCart = page.waitForResponse((response) => response.url().endsWith("/api/preferences") && response.request().method() === "PUT" && response.ok());
  await card.getByRole("button", { name: "أضف إلى السلة", exact: true }).click();
  await savedCart;
  await page.goto(base + "/checkout", { waitUntil: "networkidle" });
  await page.locator('input[name="consent"]').check();
  await page.getByRole("button", { name: "حفظ طلب الاهتمام", exact: true }).click();
  await page.locator(".order-success").waitFor();
  await page.getByRole("link", { name: "عرض طلباتي", exact: true }).click();
  await page.locator(".orders-grid").getByText(`${listingTitle} × 1`, { exact: true }).waitFor();
  await page.goto(base + "/account/listings", { waitUntil: "networkidle" });
  await page.getByRole("button", { name: "حذف الإعلان", exact: true }).click();
  await page.locator(".delete-confirm").getByRole("button", { name: "حذف الإعلان", exact: true }).click();
  await page.locator(".managed-listing").waitFor({ state: "detached" });
  await page.goto(base + "/contact", { waitUntil: "networkidle" });
  await page.locator('input[name="name"]').fill("فحص واجهة رابط");
  await page.locator('input[name="email"]').fill(`qa-ui-${unique}@example.test`);
  await page.locator('textarea[name="message"]').fill("رسالة تجريبية لفحص حفظ نموذج التواصل من المتصفح.");
  await page.locator('input[name="consent"]').check();
  await page.getByRole("button", { name: "إرسال الرسالة", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "تم حفظ رسالتك" }).waitFor();
  for (const route of ["/terms", "/privacy", "/returns", "/contact", "/orders"]) {
    await page.goto(base + route, { waitUntil: "networkidle" });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow: ${route}`);
  }
  assert.deepEqual(errors, []);
  await browser.close();
  console.log("PASS: images, dark-mode persistence, mobile layout, registration, listing publish/search/delete, legal/contact/order pages and no browser errors.");
})().catch((error) => { console.error(error); process.exit(1); });
